import asyncio, sys
sys.path.insert(0, __import__("os").path.dirname(__import__("os").path.abspath(__file__))); from mock import *
from playwright.async_api import async_playwright
# Model Guide: add your own models next to the scanned ones (kept in this browser), edit, copy for Claude, delete.
async def main():
    serve()
    async with async_playwright() as pw:
        b = await pw.chromium.launch(); ctx = await b.new_context(viewport={"width": 1400, "height": 900})
        await ctx.grant_permissions(["clipboard-read", "clipboard-write"], origin="http://localhost:8765")
        await setup(ctx); await setup_mexc(ctx)
        pg = await ctx.new_page(); errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.on("dialog", lambda d: asyncio.ensure_future(d.accept()))
        await pg.route_web_socket("wss://fstream.binance.com/stream", lambda ws: None)
        await pg.goto("http://localhost:8765/"); await pg.evaluate("() => localStorage.clear()"); await pg.reload(); await ready(pg)
        q = lambda js: pg.evaluate(js)
        await q("() => goPage('guide')"); await asyncio.sleep(0.3)
        n0 = await q("() => document.querySelectorAll('#guide .gchip[data-m]').length")
        print("1) scanned models:", n0, "| add button:", await q("() => document.getElementById('gAdd').textContent"))
        await pg.click("#gAdd"); await asyncio.sleep(0.2)
        await pg.click("#gfSave"); m1 = await q("() => document.getElementById('gfMsg').innerText")
        await pg.fill("#gfName", "nbb"); await pg.click("#gfSave"); m2 = await q("() => document.getElementById('gfMsg').innerText")
        print("2) no name:", m1, "| a scanned model's name:", m2)
        if "name first" not in m1 or "already" not in m2: errs.append("name checks missing")
        await pg.fill("#gfName", "London sweep"); await pg.fill("#gfTf", "5m")
        await pg.fill("#gfWhat", "Asia range swept at the London open, then a 5m break back inside.")
        await pg.fill("#gfRules", "Asia high or low swept after 3 PM\n\n  <img src=x onerror=alert(1)> close back inside the range  \nBreak of the last 5m swing")
        await q("() => renderGuide()")          # a scan finishing while you type: the form stays as it is
        kept = await q("() => [!!document.getElementById('gfName'), document.getElementById('gfName').value, document.getElementById('gfRules').value.split('\\n').length]")
        print("3) a new scan while typing keeps the form:", kept)
        if kept != [True, "London sweep", 4]: errs.append(f"the form was reset by a scan: {kept}")
        await pg.fill("#gfTrade", "Enter on the break, stop beyond the sweep, 2R"); await pg.click("#gfSave"); await asyncio.sleep(0.2)
        view = await q("() => [document.querySelector('#guide .gchip.on').textContent.trim(), document.querySelector('#guide .gcol h3').textContent.trim(), [...document.querySelectorAll('#guide .gcol ul li')].map(li => li.textContent), document.querySelectorAll('#guide img').length]")
        print("4) saved:", view)
        if view[2] != ["Asia high or low swept after 3 PM", "<img src=x onerror=alert(1)> close back inside the range", "Break of the last 5m swing"] or view[3]: errs.append(f"rules not saved as plain text: {view}")
        await pg.reload(); await ready(pg); await q("() => goPage('guide')"); await asyncio.sleep(0.2)
        chips = await q("() => [...document.querySelectorAll('#guide .gchip.gmine')].map(b => b.textContent.trim())")
        print("5) after reload:", chips)
        if chips != ["📌 London sweep yours"]: errs.append(f"model not kept: {chips}")
        await pg.click("#guide .gchip.gmine"); await pg.click("#gEdit"); await asyncio.sleep(0.2)
        await pg.fill("#gfName", "London sweep (Gold)"); await pg.fill("#gfIcon", "🌅"); await pg.click("#gfSave"); await asyncio.sleep(0.2)
        print("6) edited:", await q("() => [document.querySelector('#guide .gcol h3').textContent.trim(), JSON.parse(localStorage.getItem('finder-my-models')).length]"))
        await pg.click("#gCopy"); await asyncio.sleep(0.3)
        clip = await q("() => navigator.clipboard.readText()")
        print("7) copy for Claude:", clip.split("\n")[:3])
        if "Name: London sweep (Gold)" not in clip or "- Break of the last 5m swing" not in clip: errs.append("copy text incomplete")
        await pg.click("#guide .gchip[data-m=NBB]"); await asyncio.sleep(0.2)
        print("8) back to a scanned model:", await q("() => document.querySelector('#guide .gcol h3').textContent.trim().slice(0, 40)"))
        await pg.click("#guide .gchip.gmine"); await pg.click("#gDel"); await asyncio.sleep(0.3)
        left = await q("() => [document.querySelectorAll('#guide .gchip.gmine').length, document.querySelector('#guide .gchip.on').dataset.m, JSON.parse(localStorage.getItem('finder-my-models')).length]")
        print("9) deleted:", left)
        if left != [0, "NBB", 0]: errs.append(f"delete failed: {left}")
        await pg.set_viewport_size({"width": 390, "height": 800}); await pg.click("#gAdd"); await asyncio.sleep(0.2)
        print("10) phone width, no sideways scroll:", await q("() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1"))
        print("errors:", errs or "none")
        await b.close()
asyncio.run(main())
